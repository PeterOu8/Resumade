import { Document, Page, Text, View, StyleSheet } from '@react-pdf/renderer';
import type { TailorResult } from '@/lib/types';

const styles = StyleSheet.create({
  page: { padding: 40, fontSize: 12, fontFamily: 'Helvetica' },
  meta: { marginBottom: 16 },
  body: { lineHeight: 1.4 },
  para: { marginBottom: 10 },
});

export default function CoverLetterPDF({ data }: { data: TailorResult }) {
  const text =
    data.coverLetter || 'Cover letter was not generated by the model.';
  const paras = text
    .split(/\n{2,}/)
    .map((s) => s.trim())
    .filter(Boolean);

  return (
    <Document>
      <Page size="A4" style={styles.page}>
        <View style={styles.meta}>
          <Text>Dear Hiring Manager</Text>
        </View>
        <View style={styles.body}>
          {paras.map((p, i) => (
            <Text key={i} style={styles.para}>
              {p}
            </Text>
          ))}
          <Text>Kind regards,</Text>
          <Text>Li-Sung Ou</Text>
        </View>
      </Page>
    </Document>
  );
}
